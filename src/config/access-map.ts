// Who may reach each way into the app. access-map.test.ts fails CI when a route, a server action or
// a page isn't listed here, and the access proof (src/security/access-proof, ACCESS_PROOF=1) attacks
// each one as what it says it is. See docs/security/access-proof.md.
//
// - "signed-in": a person, past two-factor and the Terms. Nobody else gets in; a person gets only
//   their own rows.
// - "admin": ADMIN_EMAILS with two-factor; a 404 to everyone else.
// - "cron": Vercel Cron, with CRON_SECRET.
// - "webhook": another company, with a signature checked before anything is believed.
// - public(why): anyone, with the reason it's safe. A link that carries its own secret is public.

export type AccessKind = "public" | "signed-in" | "admin" | "cron" | "webhook";
export type Access = Exclude<AccessKind, "public"> | { kind: "public"; why: string };

const public_ = (why: string): Access => ({ kind: "public", why });

export const accessKind = (access: Access): AccessKind =>
  typeof access === "string" ? access : access.kind;

