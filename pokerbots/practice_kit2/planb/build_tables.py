#!/usr/bin/env python3
"""Offline equity tables for planb_bot (Pocket Swap Hold'em).

Monte Carlo with the kit's evaluator: 8 random hands + flop, every hand then
makes the draw with planb_bot's own draw policy, then turn + river.  For each
deal, each hero h (rotated over all 8 hands) and each k = 1..7, opponents are
the next k hands; hero's share = 1 if it beats them all, 1/(number tied) if
tied for best, else 0.

Keys:
  PRE  (class, k)                                  class like 'AKs', 'T9o', '77p'
  POST (street, my category, board category, flush-draw flag, k)
       flop: my category BEFORE the draw (decision is before the draw);
       turn/river: after the draw.

    python3 planb/build_tables.py --seconds 120 --out planb/tables_out.py
    python3 planb/build_tables.py --splice        # paste into planb_bot.py
"""

import argparse
import multiprocessing as mp
import random
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
KIT = HERE.parent
sys.path.insert(0, str(KIT))
sys.path.insert(0, str(HERE))

from simkit.cards import evaluate, full_deck  # noqa: E402
import planb_bot as B  # noqa: E402

MIN_SAMPLES = 20


def worker(args):
    seconds, seed = args
    rng = random.Random(seed)
    deck = full_deck()
    pre = {}
    post = {}
    t_end = time.time() + seconds
    deals = 0
    while time.time() < t_end:
        for _ in range(50):
            rng.shuffle(deck)
            holes = [deck[2 * i:2 * i + 2] for i in range(8)]
            flop = deck[16:19]
            pos = 19
            classes = [B.hand_class(h) for h in holes]
            fbc = B.category(flop)
            flop_keys = [("flop", B.category(h + flop), fbc,
                          B.flush_draw(h, flop)) for h in holes]
            new_holes = []
            for h in holes:
                d = B.choose_discard(h, flop)
                if d is None:
                    new_holes.append(h)
                else:
                    new_holes.append([c if c != d else deck[pos] for c in h])
                    pos += 1
            turn_board = flop + [deck[pos]]
            board = turn_board + [deck[pos + 1]]
            tbc = B.category(turn_board)
            rbc = B.category(board)
            scores = [evaluate(h + board) for h in new_holes]
            for hero in range(8):
                h = new_holes[hero]
                keys = (flop_keys[hero],
                        ("turn", B.category(h + turn_board), tbc,
                         B.flush_draw(h, turn_board)),
                        ("river", B.category(h + board), rbc, 0))
                mine = scores[hero]
                beaten = False
                ties = 0
                for k in range(1, 8):
                    o = scores[(hero + k) % 8]
                    if o > mine:
                        beaten = True
                    elif o == mine:
                        ties += 1
                    share = 0.0 if beaten else 1.0 / (ties + 1)
                    a = pre.setdefault((classes[hero], k), [0.0, 0])
                    a[0] += share
                    a[1] += 1
                    for kk in keys:
                        a = post.setdefault(kk + (k,), [0.0, 0])
                        a[0] += share
                        a[1] += 1
        deals += 50
    return pre, post, deals


def merge(into, part):
    for key, (s, n) in part.items():
        a = into.setdefault(key, [0.0, 0])
        a[0] += s
        a[1] += n


def render(pre, post):
    lines = ["PRE = {"]
    for key in sorted(pre):
        s, n = pre[key]
        if n >= MIN_SAMPLES:
            lines.append(f"    {key!r}: {s / n:.4f},")
    lines.append("}")
    lines.append("POST = {")
    for key in sorted(post):
        s, n = post[key]
        if n >= MIN_SAMPLES:
            lines.append(f"    {key!r}: {s / n:.4f},")
    lines.append("}")
    return "\n".join(lines) + "\n"


def splice(tables_path, bot_path):
    text = Path(bot_path).read_text()
    tables = Path(tables_path).read_text()
    a = text.index("# BEGIN TABLES")
    b = text.index("# END TABLES")
    head = text[:a] + "# BEGIN TABLES (generated by planb/build_tables.py)\n"
    Path(bot_path).write_text(head + tables + text[b:])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--seconds", type=float, default=120)
    ap.add_argument("--procs", type=int, default=mp.cpu_count())
    ap.add_argument("--out", default=str(HERE / "tables_out.py"))
    ap.add_argument("--splice", action="store_true")
    args = ap.parse_args()
    if args.splice:
        splice(args.out, HERE / "planb_bot.py")
        print("spliced", args.out, "into planb_bot.py")
        return
    with mp.Pool(args.procs) as pool:
        parts = pool.map(worker, [(args.seconds, 1000 + i)
                                  for i in range(args.procs)])
    pre, post, deals = {}, {}, 0
    for p, q, d in parts:
        merge(pre, p)
        merge(post, q)
        deals += d
    Path(args.out).write_text(render(pre, post))
    print(f"{deals} deals; {len(pre)} preflop keys, "
          f"{sum(1 for v in post.values() if v[1] >= MIN_SAMPLES)} postflop keys "
          f"-> {args.out}")


if __name__ == "__main__":
    main()
