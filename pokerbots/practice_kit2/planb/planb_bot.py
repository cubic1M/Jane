def _ids(state):
    n = state["num_seats"]
    ring = S["ring"]
    if ring is None or len(ring) != n:
        ring = list(range(n))
        S["ring"] = ring
    me = state["my_seat"]
    return lambda seat: ring[(seat - me) % n]


def _rate(table, pid):
    f, n = table.get(pid, (0, 0))
    return (f + 1.0) / (n + 2.0)


def _record(summary):
    n = len(summary["chips_after"])
    ring = S["ring"]
    if ring is None or len(ring) != n:
        ring = list(range(n))
        S["ring"] = ring
    me = summary["my_seat"]

    def pid(seat):
        return ring[(seat - me) % n]

    hist = summary["history"]
    for street, table in (("preflop", S["open"]), ("flop", S["post"]),
                          ("turn", S["post"]), ("river", S["post"])):
        seen = False
        done = set()
        for h in hist:
            if h["street"] != street:
                continue
            a = h["action"]
            if a == "raise":
                if seen:
                    break           # stop at the re-raise
                seen = True
                done.add(h["seat"])
                continue
            if seen and a in ("fold", "call", "check") and h["seat"] not in done:
                done.add(h["seat"])
                if h["seat"] == me:
                    continue
                rec = table.setdefault(pid(h["seat"]), [0, 0])
                rec[1] += 1
                if a == "fold":
                    rec[0] += 1
    out = {int(s) for s in summary.get("knocked_out_seats", [])}
    if out:
        S["ring"] = [ring[(s - me) % n] for s in sorted(range(n),
                     key=lambda s: (s - me) % n) if s not in out]


# ------------------------------------------------------------------ betting
def _act(kind, state, me, by=0):
    if kind == "raise":
        allin_by = me["chips_total"] - state["current_bet"]
        by = int(min(max(int(by), state["min_raise_by"]), allin_by))
        if state["can_raise"] and by > 0:
            return {"action": "raise", "amount": by}
        kind = "call"
    to_call = state["current_bet"] - me["chips_in_pot_this_round"]
    if kind == "call":
        return {"action": "call"} if to_call > 0 else {"action": "check"}
    if to_call <= 0:
        return {"action": "check"}       # never fold when checking is free
    return {"action": "fold"}


def _icm_premium(state):
    return ICM_PREMIUM * (1 + ICM_PER_BUST * (8 - state["num_seats"]))


