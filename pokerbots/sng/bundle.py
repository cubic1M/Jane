"""Bundle our sit-and-go bot into ONE self-contained Python file (kits often upload one file).

The output embeds, as source text, the modules the bot needs (engine.cards, engine.spec,
sng.ours.features, sng.ours.strength, sng.ours.icm_tag, plus a tiny engine.game stand-in),
registers them in sys.modules at import, embeds the strength table (base64 .npz) and
appends a kit-specific adapter (written on the day) that defines the kit's bot class.
Only the standard library is needed at run time (numpy only to build the bundle).

    python3 -m sng.bundle --adapter rehearsal_sng/adapter.py --variant e_shortdeck \\
        --out rehearsal_sng/submission/bot.py
"""
from __future__ import annotations

import argparse
import base64
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

MODULES = [  # (module name, source file, is_package)
    ("engine", None, True),
    ("engine.cards", "engine/cards.py", False),
    ("engine.spec", "engine/spec.py", False),
    ("sng", None, True),
    ("sng.ours", None, True),
    ("sng.ours.features", "sng/ours/features.py", False),
    ("sng.ours.strength", "sng/ours/strength.py", False),
    ("sng.ours.icm_tag", "sng/ours/icm_tag.py", False),
    ("sng.ours.anyvar", "sng/ours/anyvar.py", False),
]

GAME_STUB = '''"""Minimal engine.game for the bundled bot (actions only)."""
from dataclasses import dataclass
FOLD, CHECK, CALL, RAISE, DISCARD = "fold", "check", "call", "raise", "discard"


@dataclass(frozen=True)
class Action:
    kind: str
    amount: int = 0
    cards: tuple = ()


def Fold():
    return Action(FOLD)


def Check():
    return Action(CHECK)


def Call():
    return Action(CALL)


def RaiseTo(amount):
    return Action(RAISE, int(amount))
'''

LOADER = '''
# ---- bundled modules (generated by sng/bundle.py; do not edit) -------------------------
import base64 as _b64, io as _io, sys as _sys, types as _types


def _install(_mods):
    for _name, _src, _pkg in _mods:
        if _name in _sys.modules:
            continue
        _m = _types.ModuleType(_name)
        _m.__file__ = "/bundle/" + _name.replace(".", "/") + ("/__init__.py" if _pkg else ".py")
        if _pkg:
            _m.__path__ = []
            _m.__package__ = _name
        else:
            _m.__package__ = _name.rpartition(".")[0]
        _sys.modules[_name] = _m
        if "." in _name:
            setattr(_sys.modules[_name.rpartition(".")[0]], _name.rpartition(".")[2], _m)
        if _src:
            exec(compile(_src, _m.__file__, "exec"), _m.__dict__)


_install(_BUNDLED)


def load_bundled_table(spec):
    """Install the embedded strength table for spec; True if it matches the card rules."""
    from _nlb.sng.ours import strength as _S
    if not _TABLE_B64:
        return False
    try:   # numpy-free: the table is embedded as zlib-compressed JSON (stdlib only)
        import json as _json, zlib as _zlib
        from _nlb.sng.ours import features as _F
        _d = _json.loads(_zlib.decompress(_b64.b64decode(_TABLE_B64)))
        _ctx = _F.get_ctx(spec)
        if _d["meta"].get("signature") != repr(_ctx.sig):
            return False
        _tab = object.__new__(_S.Table)
        _tab.ctx, _tab.K, _tab.meta, _tab._memo = _ctx, int(_d["K"]), _d["meta"], {}
        _tab.pre = {k: i for i, k in enumerate(_d["pre_keys"])}
        _tab.pv = _d["pre_vals"]
        _tab.post = {k: i for i, k in enumerate(_d["post_keys"])}
        _tab.qv = _d["post_vals"]
    except Exception:
        return False
    _S.use_table(spec, _tab)
    return True


def load_bundled_any(spec):
    """Install the embedded any-variant table (discard/draw games) for icm_any."""
    if not _ANY_B64:
        return False
    import json as _json, zlib as _zlib
    from _nlb.sng.ours import anyvar as _A, features as _F
    _t = _json.loads(_zlib.decompress(_b64.b64decode(_ANY_B64)))
    _A._STRENGTH[_F.card_signature(spec)] = _A.AnyStrength(spec, table=_t)
    return True
'''


PREFIX = "_nlb"   # private top-level package: never collide with the kit's own modules
                  # (e.g. a kit simulator called engine.py)
_IMPORT_RE = __import__("re").compile(r"^(\s*)(from|import)\s+(engine|sng)\b", __import__("re").M)


def namespaced(src: str) -> str:
    """Point absolute imports of our packages at the private prefix."""
    return _IMPORT_RE.sub(lambda m: f"{m.group(1)}{m.group(2)} {PREFIX}.{m.group(3)}", src)


def table_payload(table: Path | None) -> str:
    """The strength table as base64(zlib(JSON)): loads with the standard library only
    (the tournament sandbox may not have numpy)."""
    if table is None:
        return ""
    import json
    import zlib

    import numpy as np
    with np.load(table) as z:
        d = dict(pre_keys=z["pre_keys"].tolist(), pre_vals=z["pre_vals"].ravel().tolist(),
                 post_keys=z["post_keys"].tolist(), post_vals=z["post_vals"].ravel().tolist(),
                 meta=json.loads(str(z["meta"])))
        d["K"] = d["meta"]["k_max"]
    return base64.b64encode(zlib.compress(json.dumps(d, separators=(",", ":")).encode(), 9)).decode()


def any_payload(path: Path | None) -> str:
    if path is None:
        return ""
    import zlib
    return base64.b64encode(zlib.compress(path.read_bytes(), 9)).decode()


def build(adapter: Path, table: Path | None, out: Path, any_table: Path | None = None) -> Path:
    mods = [(PREFIX, "", True)]
    for name, rel, pkg in MODULES:
        src = namespaced((ROOT / rel).read_text()) if rel else ""
        mods.append((f"{PREFIX}.{name}", src, pkg))
    mods.insert(4, (f"{PREFIX}.engine.game", GAME_STUB, False))
    parts = ["# Generated by sng/bundle.py: one-file sit-and-go bot (stdlib + numpy only).",
             f"_BUNDLED = {mods!r}",
             f"_TABLE_B64 = {table_payload(table)!r}",
             f"_ANY_B64 = {any_payload(any_table)!r}",
             LOADER,
             "# ---- kit adapter -------------------------------------------------------------------",
             namespaced(adapter.read_text())]
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(parts))
    return out


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--adapter", required=True)
    ap.add_argument("--variant", default=None, help="strength table to embed: cache/sng/strength_<v>.npz")
    ap.add_argument("--table", default=None, help="explicit table file")
    ap.add_argument("--out", required=True)
    ap.add_argument("--any-table", default=None, help="cache/sng/any_<sig>.json for icm_any (discard/draw variants)")
    a = ap.parse_args(argv)
    table = Path(a.table) if a.table else (ROOT / "cache" / "sng" / f"strength_{a.variant}.npz" if a.variant else None)
    if table is not None and not table.exists():
        raise SystemExit(f"no table {table}")
    p = build(Path(a.adapter), table, Path(a.out), Path(a.any_table) if a.any_table else None)
    print(f"wrote {p} ({p.stat().st_size / 1e6:.2f} MB)")


if __name__ == "__main__":
    main()
