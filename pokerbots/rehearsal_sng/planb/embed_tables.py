#!/usr/bin/env python3
"""Paste the PRE/POST dict literals from tables.txt into bot.py (between the TABLES markers)."""
import os
import sys

here = os.path.dirname(os.path.abspath(__file__))
tables = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, "tables.txt")
lines = [l for l in open(tables).read().splitlines() if l.startswith(("PRE = ", "POST = "))]
assert len(lines) == 2, "tables file must have PRE and POST lines"
path = os.path.join(here, "bot.py")
src = open(path).read().splitlines()
a = src.index("# BEGIN TABLES (generated by build_tables.py; do not edit by hand)")
b = src.index("# END TABLES")
src[a + 1:b] = lines
open(path, "w").write("\n".join(src) + "\n")
print(f"embedded {len(lines[0]) + len(lines[1])} chars of tables into {path}")
